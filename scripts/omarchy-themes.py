#!/usr/bin/env python3
"""Writes apple/Jolta/OmarchyThemes.swift from an Omarchy checkout.

Run by hand when Omarchy's themes change:
    python3 scripts/omarchy-themes.py <path to omarchy checkout>
"""

import pathlib
import sys
import tomllib

KEYS = {
    "background": "background",
    "dark_background": "darkBackground",
    "lighter_background": "lighterBackground",
    "foreground": "foreground",
    "selection": "selection",
    "accent": "accent",
    "yellow": "yellow",
    "blue": "blue",
    "cyan": "cyan",
    "green": "green",
    "magenta": "magenta",
    "orange": "orange",
}

# Omarchy's own fallbacks (bin/omarchy-theme-color) for keys a theme may leave out.
FALLBACKS = {"orange": "yellow"}


def fail(message):
    sys.exit(f"omarchy-themes: {message}")


def commit(checkout):
    git = checkout / ".git"
    head = (git / "HEAD").read_text().strip()
    if not head.startswith("ref: "):
        return head
    ref = head.removeprefix("ref: ")
    if (git / ref).exists():
        return (git / ref).read_text().strip()
    for line in (git / "packed-refs").read_text().splitlines():
        if line.endswith(" " + ref):
            return line.split()[0]
    fail(f"can't resolve {ref} in {git}")


def display_name(folder):
    return " ".join(word[:1].upper() + word[1:] for word in folder.split("-"))


def hex_value(theme, key, value):
    if not (isinstance(value, str) and len(value) == 7 and value.startswith("#")):
        fail(f"{theme}: {key} is {value!r}, expected #rrggbb")
    try:
        return int(value[1:], 16)
    except ValueError:
        fail(f"{theme}: {key} is {value!r}, expected #rrggbb")


def read_theme(folder):
    path = folder / "colors.toml"
    with path.open("rb") as f:
        colors = tomllib.load(f)
    for key, fallback in FALLBACKS.items():
        colors.setdefault(key, colors.get(fallback))
    missing = [k for k in ["mode", *KEYS] if colors.get(k) is None]
    if missing:
        fail(f"{path} has no {', '.join(missing)}")
    if colors["mode"] not in ("dark", "light"):
        fail(f"{path}: mode is {colors['mode']!r}, expected dark or light")
    fields = [
        f'id: "{folder.name}"',
        f'name: "{display_name(folder.name)}"',
        f'mode: .{colors["mode"]}',
    ]
    for key, swift in KEYS.items():
        fields.append(f"{swift}: 0x{hex_value(folder.name, key, colors[key]):06X}")
    return display_name(folder.name), "        OmarchyTheme(" + ", ".join(fields) + "),"


def main():
    if len(sys.argv) != 2:
        fail("usage: omarchy-themes.py <omarchy checkout>")
    checkout = pathlib.Path(sys.argv[1]).resolve()
    themes = sorted(p for p in (checkout / "themes").iterdir() if (p / "colors.toml").exists())
    if not themes:
        fail(f"no themes/*/colors.toml under {checkout}")
    rows = sorted(read_theme(t) for t in themes)
    license_text = (checkout / "LICENSE").read_text().strip()

    out = [
        f"// Generated by scripts/omarchy-themes.py from Omarchy commit {commit(checkout)}.",
        "// Don't edit by hand; rerun the script on a newer Omarchy checkout instead.",
        "//",
        "// The theme colors below come from Omarchy (https://github.com/basecamp/omarchy),",
        "// used under its MIT license:",
        "//",
        *[("// " + line).rstrip() for line in license_text.splitlines()],
        "",
        "nonisolated extension OmarchyTheme {",
        "    static let all: [OmarchyTheme] = [",
        *[row for _, row in rows],
        "    ]",
        "}",
        "",
    ]
    target = pathlib.Path(__file__).resolve().parent.parent / "apple/Jolta/OmarchyThemes.swift"
    target.write_text("\n".join(out))
    print(f"wrote {len(rows)} themes to {target}")


main()
